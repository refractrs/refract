//! Execute the app's raw WASM export without a browser, Node, or a second app binary.
use crate::Result;
use wasmi::{Config, Engine, ExternType, Linker, Module, Store, StoreLimitsBuilder};

const EXPORT: &str = "__refract_prerender_v1";
const MAX_OUTPUT: usize = 16 * 1024 * 1024;

/// Importable build data; it does not import or initialize the browser runtime.
pub fn module(html: &str) -> Result<String> {
    let value = serde_json::to_string(&serde_json::json!({ "version": 1, "html": html }))?
        .replace('<', "\\u003c")
        .replace('\u{2028}', "\\u2028")
        .replace('\u{2029}', "\\u2029");
    Ok(format!(
        "// Generated by refract build --prerender.\nexport default Object.freeze({value});\n"
    ))
}

pub const MODULE_TYPES: &str = r#"// Generated by refract build --prerender.
export interface PrerenderSnapshot {
  readonly version: 1;
  readonly html: string;
}
declare const snapshot: PrerenderSnapshot;
export default snapshot;
"#;

pub fn render(wasm: &[u8]) -> Result<String> {
    render_with_fuel(wasm, 100_000_000)
}

fn render_with_fuel(wasm: &[u8], fuel: u64) -> Result<String> {
    let mut config = Config::default();
    config.consume_fuel(true);
    let engine = Engine::new(&config);
    let module = Module::new(&engine, wasm)?;
    let limits = StoreLimitsBuilder::new()
        .memory_size(256 * 1024 * 1024)
        .build();
    let mut store = Store::new(&engine, limits);
    store.limiter(|limits| limits);
    store.set_fuel(fuel)?;
    let mut linker = Linker::new(&engine);
    // A browser application imports wasm-bindgen helpers even when its initial
    // view needs none of them. Link typed traps: never fake a browser observation.
    for import in module.imports() {
        let ExternType::Func(ty) = import.ty() else {
            return Err(format!(
                "unsupported prerender import {}::{}",
                import.module(),
                import.name()
            )
            .into());
        };
        let message = format!(
            "prerender called browser import {}::{}; move browser work into an effect",
            import.module(),
            import.name()
        );
        linker.func_new(
            import.module(),
            import.name(),
            ty.clone(),
            move |_, _, _| Err(wasmi::Error::new(message.clone())),
        )?;
    }
    let instance = linker.instantiate_and_start(&mut store, &module)?;
    let entry = instance.get_typed_func::<(), i64>(&store, EXPORT)
        .map_err(|_| "missing prerender export; add refract_web::export_prerender!(application()) to the app's WASM module")?;
    let result = entry.call(&mut store, ())? as u64;
    let pointer = (result as u32) as usize;
    let length = (result >> 32) as usize;
    if length == 0 || length > MAX_OUTPUT {
        return Err("invalid prerender output length (maximum 16 MiB)".into());
    }
    let memory = instance
        .get_memory(&store, "memory")
        .ok_or("prerender module must export memory")?;
    let mut output = vec![0; length];
    memory.read(&store, pointer, &mut output)?;
    let text = std::str::from_utf8(&output[1..])?;
    match output[0] {
        0 => Ok(text.to_owned()),
        1 => Err(format!("could not prerender application: {text}").into()),
        _ => Err("unsupported prerender output format".into()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn module_encodes_html_as_data_without_executable_interpolation() {
        let html = "</script>\"\\\n`${globalThis.bad = true}`\u{2028}\u{2029}";
        let output = module(html).unwrap();
        assert!(!output.contains('<'));
        assert!(!output.contains('\u{2028}'));
        let json = output
            .split("Object.freeze(")
            .nth(1)
            .unwrap()
            .strip_suffix(");\n")
            .unwrap();
        let snapshot: serde_json::Value = serde_json::from_str(json).unwrap();
        assert_eq!(snapshot["version"], 1);
        assert_eq!(snapshot["html"], html);
    }

    #[test]
    fn executes_raw_export_and_reads_result() {
        let wasm = wat::parse_str(
            r#"(module
            (import "browser" "unused" (func))
            (memory (export "memory") 1)
            (data (i32.const 16) "\00<div>hi</div>")
            (func (export "__refract_prerender_v1") (result i64)
                i64.const 60129542160))"#,
        )
        .unwrap(); // (14 << 32) | 16
        assert_eq!(render(&wasm).unwrap(), "<div>hi</div>");
    }

    #[test]
    fn rejects_browser_work_missing_exports_and_unbounded_execution() {
        for (wat, message) in [
            (
                r#"(module (import "browser" "window" (func $window))
                (func (export "__refract_prerender_v1") (result i64) call $window i64.const 0))"#,
                "browser import browser::window",
            ),
            ("(module)", "missing prerender export"),
            (
                r#"(module (func (export "__refract_prerender_v1") (result i64) (loop $forever br $forever) i64.const 0))"#,
                "fuel",
            ),
            (
                r#"(module (func (export "__refract_prerender_v1") (result i64) i64.const 0))"#,
                "output length",
            ),
        ] {
            assert!(render_with_fuel(&wat::parse_str(wat).unwrap(), 10_000)
                .unwrap_err()
                .to_string()
                .contains(message));
        }
    }
}
